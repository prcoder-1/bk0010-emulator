#pragma once
#include <cstdint>

namespace bk {

// Расписание обменов К1801ВМ1 для одной команды — снято с RTL-модели процессора
// (vm1.v, ревизия А) в паре с нетлистом КР1801ВП1-037 и сверено с замерами на
// реальной БК-0010-01 (тесты XOP2/XOP2N). Подробности — docs/slow-memory-timing.md.
//
// Единица времени — полутакт ЦП. Команда начинается выборкой; её первая
// микрокоманда стартует в момент S = конец выборки + 2 + хвост предыдущей команды
// (после её предвыборки). Первый обмен с операндом запрашивается через op[0].gap
// после S, каждый следующий — через gap после конца предыдущего обмена. Следующая
// выборка — через tail после конца последнего обмена, а если обменов нет — после S.
//
// «Запрос» здесь — строб DIN/DOUT минус 3 полутакта, «конец» — момент, когда ЦП
// увидел RPLY (в нотации eCat3 tools/bk-timing это одна и та же цепочка). Память
// без 037 (ПЗУ, В-В, ОЗУ плат) отвечает сразу: конец = запрос + 4 на чтение, + 5 на
// запись и + 7 на запись в чтении-модификации-записи.
//
// Часть работы микрокода видна только после быстрого обмена: ожидание окна 037 её
// прячет. Это `xf`/`pfXf` (прибавка к паузе) и `teFast` (хвост после предвыборки из
// быстрой памяти); после обмена с ДОЗУ они не действуют.
struct Vm1Step {
    char kind;          // 'R' чтение, 'W' запись, 'M' запись в чтении-модификации-записи,
                        // 'I' цикл IAKO (без памяти, всегда быстрый)
    uint8_t gap;
    uint8_t xf = 0;     // прибавка к gap, если предыдущий обмен был быстрым
};

struct Vm1Sched {
    uint8_t n = 0;          // обменов с операндами (без выборки)
    Vm1Step op[7];
    uint8_t tail = 0;
    uint8_t pfXf = 0;       // прибавка к tail, если последний обмен был быстрым
    bool early = false;     // хвост 2 после предвыборки из ДОЗУ («ранняя предвыборка»)
    uint8_t teFast = 0;     // хвост после предвыборки из быстрой памяти
};

// false — для команды расписания нет (HALT, WAIT, RESET, MARK, недопустимые коды):
// время считается по старой таблице.
bool vm1Schedule(uint16_t ir, Vm1Sched& s);

// Вход в прерывание или ловушку по фиксированному вектору (IRQ2, СТОП, T-бит) и
// векторное прерывание с циклом IAKO (клавиатура). Шаблон — из симуляции кристалла
// в eCat3. «Выборка» в начале — отброшенная предвыборка следующей команды.
void vm1InterruptSchedule(bool iako, Vm1Sched& s);

} // namespace bk
