#pragma once
#include <cstdint>

namespace bk {

// Расписание обменов К1801ВМ1 для одной команды — снято с RTL-модели процессора
// (vm1.v, ревизия А) в паре с нетлистом КР1801ВП1-037 и сверено с замерами на
// реальной БК-0010-01 (тесты XOP2/XOP2N). Подробности — docs/slow-memory-timing.md.
//
// Единица времени — полутакт ЦП. Команда начинается выборкой; её первая
// микрокоманда стартует в момент S = конец выборки + 2 (после обычной выборки) или
// + 4 (если выборку сделала предыдущая команда «ранней предвыборкой»). Первый обмен с
// операндом запрашивается через op[0].gap после S, каждый следующий — через gap после
// конца предыдущего обмена. Следующая выборка — через tail после конца последнего
// обмена, а если обменов с операндами нет — после S.
struct Vm1Step { char kind; uint8_t gap; };   // kind: 'R' чтение, 'W' запись

struct Vm1Sched {
    uint8_t n = 0;          // обменов с операндами (без выборки)
    Vm1Step op[7];
    uint8_t tail = 0;
    bool early = false;     // следующую команду выбирает «ранняя предвыборка»
};

// false — для команды расписания нет (HALT, WAIT, RESET, MARK, недопустимые коды):
// время считается по старой таблице.
bool vm1Schedule(uint16_t ir, Vm1Sched& s);

} // namespace bk
