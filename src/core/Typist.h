#pragma once
#include <string_view>

namespace bk {

class Board;

// Регистр РУС/ЛАТ так, как его видит система: монитор БК-0010 держит его в байте 043
// (0200 — РУС), БОС БК-0011М — в байте 0455 системной страницы 7. Верно, только пока
// клавиатуру обслуживает сама система (вектор 060 — её обработчик): 1 — РУС, 0 — ЛАТ,
// -1 — неизвестно (клавиатура у программы).
int systemCyrillic(Board& b);

struct TypeResult {
    int chars = 0, total = 0;   // символов набрано / в строке
    int codes = 0;              // нажато кодов (с РУС/ЛАТ)
    int frames = 0;
};

// Набрать строку UTF-8 (кириллица — с РУС/ЛАТ, «\n» — ВВОД), как человек: каждая клавиша
// держится holdFrames кадров (игры, опрашивающие бит 6 0177716, видят её), после
// отпускания — gapFrames. Следующая клавиша — когда предыдущий код прочитан, а пока
// клавиатуру обслуживает монитор БК-0010 — ещё и когда ЦП снова в EMT 6: на входе он
// читает 0177662 и выбрасывает код, нажатый раньше. cyrState — регистр, как его
// помнит набирающий; перед каждым символом сверяется с systemCyrillic().
TypeResult typeText(Board& b, std::string_view utf8, bool& cyrState,
                    int holdFrames = 2, int gapFrames = 2, int budget = 600);

} // namespace bk
