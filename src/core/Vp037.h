#pragma once
#include <cstdint>

namespace bk {

// Потактовая модель арбитража КР1801ВП1-037 — системного/видеоконтроллера БК-0010,
// управляющего всем динамическим ОЗУ (оба банка 000000..077777 — один массив 16К×16).
//
// Порт свободнобегущих счётчиков из RTL-модели кристалла `037/rtl/va_037.v`
// (репозиторий 1801BM1/k1801): счётчик пикселей PC (mod-8), счётчик слов строки
// VA[5:1], строчный счётчик LC, гейты HGATE/VGATE. Тактируется в домене CLKIN
// (пиксельный такт 037): CLC = 6 МГц, ЦП = CLC/2 = 3 МГц ⇒ 1 такт ЦП = 2 такта CLKIN.
//
// Геометрия, вытекающая из счётчиков (проверяется юнит-тестом):
//   строка  = 384 CLKIN = 32 видимых слова (~HGATE) + 16 слов гашения (HGATE)
//   кадр    = 320 строк  = 256 видимых (~VGATE) + 64 строки кадрового гашения (VGATE)
//   ⇒ 122880 CLKIN/кадр = 61440 тактов ЦП. Отсюда и кадровая частота БК: 3 МГц / 61440
//     = 48,83 Гц, а не 50 Гц. Кадр эмулятора берётся ровно таким же (Board::ticksPerFrame),
//     поэтому syncToFrameTop() ничего не обрезает — фазы совпадают точно.
//
// В малом экране (M256=0) видеовыборка (а с ней ожидания) идёт только на первых
// 64 видимых строках (LC6&LC7), в полном (M256=1) — на всех 256. Это следует прямо
// из RTL и совпадает с «малый экран = 64 строки».
//
// Из модели нужно только положение луча: где он стоит — для построчной отрисовки и
// для отладчика. Шину Q-bus (nAD/nSYNC/nDIN/nDOUT/nRPLY) и видеовыход не моделируем.
//
// Тактов ожидания ЦП здесь НЕТ, и это проверено железом. Окно доступа процессора к
// ДОЗУ задаёт свободнобегущий PC[2:0] — оно открывается раз в 8 тактов CLKIN (= 4
// такта ЦП) ВСЕГДА, независимо от развёртки, поэтому цена доступа к ДОЗУ от фазы
// кадра не зависит: тест `45com-lo` (©Manwe) на реальной БК-0010.01 даёт ровно целые
// значения (`COM R0` = 12.0 при выборке команды из ДОЗУ), а любое ожидание по WTI
// размазало бы их по фазам в дробные. Само квантование окном считает модель шины
// ВМ1 (`Board::busStep`, Vm1Timing.h).
class Vp037 {
public:
    Vp037() { reset(); }

    // Начальные состояния как в RTL (posedge RESET): кадровое гашение.
    void reset();

    // Выставить фазу на начало видимого поля (VGATE только что сброшен). Эмулятор
    // ресинкает сюда на каждом кадровом IRQ (= VSYNC 037). Кадр эмулятора равен кадру
    // 037 (61440 тактов ЦП), так что ресинк лишь снимает накопленную погрешность и
    // ничего не отбрасывает: видимые 256 строк (49152 такта) и 64 строки гашения
    // укладываются в кадр целиком.
    void syncToFrameTop();

    // Режим экрана из бита 9 (01000) регистра 0177664: 1 = полный экран (256 строк),
    // 0 = малый экран (видеовыборка только на 64 строках).
    void setM256(bool full) { m256_ = full; }
    bool m256() const { return m256_; }

    // Продвинуть счётчики на `clkin` тактов CLKIN.
    void tick(int clkin);

    // Луч в активной части развёртки: 037 занимает шину видеовыборкой в своих
    // циклах. На цену доступа ЦП это не влияет (см. комментарий к классу).
    bool inActiveDisplay() const {
        return !vgate_ && !hgate_ && (m256_ || ((lc_ & 0300) == 0300)); // LC6&LC7
    }

    // --- Отладка/тесты ---
    int  pc()    const { return pc_; }
    bool hgate() const { return hgate_; }
    bool vgate() const { return vgate_; }
    int  lc()    const { return lc_; }

    // Номер строки развёртки от начала кадра (0..319; видимые — первые 256).
    // Считается по тактам CLKIN, а не из LC: LC — убывающий счётчик с XOR-переключением
    // старших бит, и восстанавливать из него «строку экрана» хрупко. Ресинк — в
    // syncToFrameTop(), который эмулятор зовёт на каждом кадровом прерывании.
    static constexpr int CLKIN_PER_LINE  = 384;
    static constexpr int LINES_PER_FRAME = 320;   // 256 видимых + 64 кадрового гашения
    static constexpr int CLKIN_PER_FRAME = CLKIN_PER_LINE * LINES_PER_FRAME;  // 122880
    int scanline() const {
        // По модулю кадра: на самой границе frameClk_ успевает дойти до 122880, и без
        // приведения получалась бы несуществующая «строка 320».
        return static_cast<int>(frameClk_ / CLKIN_PER_LINE) % LINES_PER_FRAME;
    }

    // Упаковка фазы развёртки для снимка состояния: где именно стоял луч, влияет на
    // такты ожидания ДОЗУ, а с построчной отрисовкой будет влиять и на картинку.
    uint32_t pack() const {
        return static_cast<uint32_t>(pc_) | (static_cast<uint32_t>(va51_) << 8)
             | (static_cast<uint32_t>(lc_) << 16)
             | (hgate_ ? 1u << 24 : 0) | (vgate_ ? 1u << 25 : 0) | (m256_ ? 1u << 26 : 0);
    }
    void unpack(uint32_t v) {
        pc_    = static_cast<uint8_t>(v & 0xFF);
        va51_  = static_cast<uint8_t>((v >> 8) & 0xFF);
        lc_    = static_cast<uint8_t>((v >> 16) & 0xFF);
        hgate_ = (v >> 24) & 1;
        vgate_ = (v >> 25) & 1;
        m256_  = (v >> 26) & 1;
    }

private:
    uint8_t  pc_    = 0;      // PC[2:0]  — счётчик пикселей в слове (mod-8)
    uint8_t  va51_  = 0;      // VA[5:1]  — счётчик слов в строке (VA5..VA1)
    uint8_t  lc_    = 0xFF;   // LC[7:0]  — строчный счётчик
    bool     hgate_ = false;  // HGATE    — горизонтальное гашение
    bool     vgate_ = true;   // VGATE    — кадровое гашение (1 = гашение)
    bool     m256_  = true;   // полный (true) / малый (false) экран
    uint32_t frameClk_ = 0;   // тактов CLKIN от начала кадра (для scanline())
};

} // namespace bk
